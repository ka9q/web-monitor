#!/usr/bin/env python3
"""Remove the known local install files, preserving configuration and logs."""
import argparse
import pathlib
import shutil


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--destdir', default='')
    for name in ('bindir', 'libdir', 'venv', 'unitdir'):
        parser.add_argument('--' + name, required=True)
    args = parser.parse_args()
    def target(value):
        path = pathlib.Path(value)
        if not path.is_absolute() or '..' in path.parts or path == pathlib.Path('/'):
            parser.error('installation paths must be absolute, non-root paths without ..')
        return pathlib.Path(args.destdir) / str(path).lstrip('/') if args.destdir else path
    bindir, libdir, venv, unitdir = map(target, (args.bindir, args.libdir, args.venv, args.unitdir))
    # Recursive deletion is confined to a recognizable virtual environment.
    if venv == libdir or venv in libdir.parents:
        parser.error('VENV must not contain the application directory')
    if venv.exists() and not venv.is_symlink() and not (venv / 'pyvenv.cfg').is_file():
        parser.error('VENV exists without pyvenv.cfg; refusing recursive removal')
    files = [bindir / 'web-monitor', unitdir / 'web-monitor.service',
             target('/etc/rsyslog.d/30-web-monitor.conf'),
             target('/etc/logrotate.d/web-monitor')]
    files += [libdir / name for name in ('server.py', 'core.py', 'demo.py', 'discovery.py')]
    static = libdir / 'static'
    if static.is_symlink():
        files.append(static)
    else:
        files += [static / name for name in ('index.html', 'app.js', 'style.css')]
    for path in files:
        if path.is_symlink() or path.is_file():
            path.unlink()
            print('Removed', path)
    if venv.is_symlink():
        venv.unlink()
    elif venv.exists():
        shutil.rmtree(venv)
        print('Removed virtual environment', venv)
    # Remove only generated bytecode for application modules.
    cache = libdir / '__pycache__'
    if cache.is_dir() and not cache.is_symlink():
        for module in ('server', 'core', 'demo', 'discovery'):
            for path in cache.glob(module + '.*.pyc'):
                path.unlink()
    for path in (static, cache, libdir):
        if not path.is_symlink():
            try:
                path.rmdir()
            except (FileNotFoundError, OSError):
                pass  # Keep directories containing unrelated files.
    print('Configuration and logs preserved. No services were stopped or reloaded.')
    print('Reinstall the Debian package before starting it: application paths overlap.')


if __name__ == '__main__':
    main()
